//! Cargo workspace layout, read from the repository's `Cargo.toml` manifests.
//!
//! A workspace member is *intra-repo*: `use model::channel::Channel` inside
//! `crates/hub` names a crate that lives in this repository, so treating it as
//! a third-party crate would silently truncate the closure. This module reads
//! only what module resolution needs, once per index build:
//!
//! - the workspace `members` (with `*` wildcards and `exclude`),
//! - each member's package name, `[lib] name` (default: the package name with
//!   `-` replaced by `_`) and `[lib] path` (default: `src/lib.rs`),
//! - `path` dependencies from the member manifests and
//!   `[workspace.dependencies]`, so a renamed dependency (`model = { path =
//!   "../model" }`) still maps to the crate that provides it.
//!
//! Nothing is compiled. crates.io is never consulted; a dependency without
//! `path` stays unresolved. `[patch]` / `[replace]`, vendored sources and
//! modules generated by build scripts are out of scope, and so are nested
//! workspaces (only the workspace at the project root is read).

use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};

use serde::Deserialize;

/// One crate of the repository: a workspace member or the root package.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct Crate {
    /// Name a `use` statement writes, underscores included (`session_store`).
    pub name: String,
    /// Crate directory relative to the project root (`""` for the root package).
    pub root: String,
    /// Directory holding the library sources (`crates/model/src`).
    pub src: String,
    /// Library root file (`crates/model/src/lib.rs`).
    pub lib: String,
}

/// The crate map of one repository. Empty when there is no readable
/// `Cargo.toml`, which keeps every previous behaviour for other projects.
#[derive(Debug, Clone, Default)]
pub struct Workspace {
    crates: Vec<Crate>,
    /// Name used in `use` -> crate index, for renamed `path` dependencies.
    aliases: BTreeMap<String, usize>,
}

impl Workspace {
    /// Reads the manifests under `root`. Cheap and side-effect free: the root
    /// manifest plus one small file per member, re-read on every index build so
    /// editing a `Cargo.toml` takes effect without clearing the cache.
    pub fn discover(root: &Path) -> Workspace {
        let Some(root_manifest) = read_manifest(&root.join("Cargo.toml")) else {
            return Workspace::default();
        };

        let mut dirs = match &root_manifest.workspace {
            Some(workspace) => member_dirs(root, workspace),
            None => Vec::new(),
        };
        // A root `[package]` is an implicit member, virtual manifest or not.
        if root_manifest.package.is_some() && !dirs.iter().any(|dir| dir == root) {
            dirs.push(root.to_path_buf());
        }

        let mut workspace = Workspace::default();
        let mut manifests: Vec<(String, Manifest)> = Vec::new();
        for dir in dirs {
            let Some(rel) = relative(root, &dir) else {
                continue;
            };
            let Some(manifest) = read_manifest(&dir.join("Cargo.toml")) else {
                continue;
            };
            if let Some(crate_entry) = crate_of_manifest(&rel, &dir, &manifest) {
                if !workspace
                    .crates
                    .iter()
                    .any(|known| known.name == crate_entry.name)
                {
                    workspace.crates.push(crate_entry);
                }
            }
            manifests.push((rel, manifest));
        }
        // Longest directory first: `crate_of` scans in order, and the root
        // package (`""`) is a prefix of every other member.
        workspace.crates.sort_by(|left, right| {
            right
                .root
                .len()
                .cmp(&left.root.len())
                .then_with(|| left.root.cmp(&right.root))
        });

        let mut path_dependencies: Vec<(String, String)> = Vec::new();
        if let Some(section) = &root_manifest.workspace {
            for (key, dependency) in &section.dependencies {
                if let Some(path) = dependency
                    .path()
                    .and_then(|path| resolve_relative("", path))
                {
                    path_dependencies.push((key.clone(), path));
                }
            }
        }
        for (rel, manifest) in &manifests {
            for (key, dependency) in manifest
                .dependencies
                .iter()
                .chain(manifest.dev_dependencies.iter())
                .chain(manifest.build_dependencies.iter())
            {
                if let Some(path) = dependency
                    .path()
                    .and_then(|path| resolve_relative(rel, path))
                {
                    path_dependencies.push((key.clone(), path));
                }
            }
        }
        for (key, target) in path_dependencies {
            let Some(member) = workspace
                .crates
                .iter()
                .position(|known| known.root == target)
            else {
                continue;
            };
            let name = crate_name(&key);
            if workspace.crates[member].name != name {
                workspace.aliases.insert(name, member);
            }
        }

        workspace
    }

    /// Whether any `Cargo.toml` produced a crate map.
    #[cfg(test)]
    pub fn is_empty(&self) -> bool {
        self.crates.is_empty()
    }

    /// The crate a `use` statement can name, including renamed dependencies.
    pub fn crate_named(&self, name: &str) -> Option<&Crate> {
        let position = match self.aliases.get(name) {
            Some(position) => *position,
            None => self.crates.iter().position(|known| known.name == name)?,
        };
        self.crates.get(position)
    }

    /// The crate that owns a file (`crates/a/src/lib.rs` -> crate `a`).
    pub fn crate_of(&self, rel: &str) -> Option<&Crate> {
        self.crates.iter().find(|known| within(rel, &known.root))
    }

    /// The crate whose directory is exactly `dir`, for a crate-level seed.
    pub fn crate_at_dir(&self, dir: &str) -> Option<&Crate> {
        let dir = dir.trim_end_matches('/');
        self.crates.iter().find(|known| known.root == dir)
    }

    /// Every indexed source of `krate`, `src/lib.rs` first so a crate seed
    /// reads like a crate: root, then the modules in path order. The lib root
    /// stays in the list even when it is not indexed, so the caller can report
    /// it as missing instead of silently dropping the crate.
    pub fn files_of<'a>(&self, krate: &Crate, rels: impl Iterator<Item = &'a str>) -> Vec<String> {
        let mut files: Vec<String> = rels
            .filter(|rel| rel.ends_with(".rs") && within(rel, &krate.src))
            .map(str::to_string)
            .collect();
        files.sort();
        files.dedup();
        files.retain(|rel| *rel != krate.lib);
        files.insert(0, krate.lib.clone());
        files
    }
}

/// The name Rust code uses for a manifest key (`session-store` ->
/// `session_store`); Cargo does the same for package and lib names.
fn crate_name(key: &str) -> String {
    key.replace('-', "_")
}

/// Whether `rel` is `dir` itself or lives underneath it. The empty directory is
/// the project root, so every path is inside it.
fn within(rel: &str, dir: &str) -> bool {
    dir.is_empty() || rel == dir || rel.starts_with(&format!("{dir}/"))
}

/// `root`-relative, `/`-separated directory of `dir`, or `None` when it is
/// outside the project.
fn relative(root: &Path, dir: &Path) -> Option<String> {
    let rel = dir.strip_prefix(root).ok()?;
    let parts: Vec<&str> = rel
        .components()
        .filter_map(|component| component.as_os_str().to_str())
        .filter(|component| !component.is_empty() && *component != ".")
        .collect();
    Some(parts.join("/"))
}

/// Joins a `path` dependency onto its manifest directory and collapses `.` and
/// `..`. Returns `None` when the dependency points outside the project.
fn resolve_relative(base: &str, path: &str) -> Option<String> {
    let mut parts: Vec<String> = if base.is_empty() {
        Vec::new()
    } else {
        base.split('/').map(str::to_string).collect()
    };
    for segment in path.split(['/', '\\']) {
        match segment {
            "" | "." => {}
            ".." => {
                parts.pop()?;
            }
            segment => parts.push(segment.to_string()),
        }
    }
    Some(parts.join("/"))
}

/// Member directories, `*` wildcards expanded one level per path segment, minus
/// the workspace's `exclude` list.
fn member_dirs(root: &Path, workspace: &WorkspaceSection) -> Vec<PathBuf> {
    let excluded = &workspace.exclude;
    let mut dirs: Vec<PathBuf> = Vec::new();
    for pattern in &workspace.members {
        for dir in expand_member(root, pattern) {
            let Some(rel) = relative(root, &dir) else {
                continue;
            };
            if excluded.contains(&rel) {
                continue;
            }
            if !dirs.contains(&dir) {
                dirs.push(dir);
            }
        }
    }
    dirs
}

fn expand_member(root: &Path, pattern: &str) -> Vec<PathBuf> {
    let mut current = vec![root.to_path_buf()];
    for segment in pattern.split('/') {
        if segment.is_empty() || segment == "." {
            continue;
        }
        let mut next: Vec<PathBuf> = Vec::new();
        for dir in &current {
            if segment.contains('*') {
                let Ok(entries) = fs::read_dir(dir) else {
                    continue;
                };
                let mut matches: Vec<PathBuf> = entries
                    .flatten()
                    .map(|entry| entry.path())
                    .filter(|path| path.is_dir())
                    .filter(|path| {
                        path.file_name()
                            .and_then(|name| name.to_str())
                            .is_some_and(|name| segment_matches(segment, name))
                    })
                    .collect();
                matches.sort();
                next.extend(matches);
            } else {
                let path = dir.join(segment);
                if path.is_dir() {
                    next.push(path);
                }
            }
        }
        current = next;
    }
    current
}

/// One `*` per segment, matched as a prefix/suffix pair (`crates/*`, `*-core`).
fn segment_matches(pattern: &str, name: &str) -> bool {
    match pattern.split_once('*') {
        None => pattern == name,
        Some((prefix, suffix)) => {
            name.len() >= prefix.len() + suffix.len()
                && name.starts_with(prefix)
                && name.ends_with(suffix)
        }
    }
}

/// The crate a member manifest describes, or `None` for a member without a
/// library target (a binary-only crate cannot be `use`d by name).
fn crate_of_manifest(rel: &str, dir: &Path, manifest: &Manifest) -> Option<Crate> {
    let package = manifest.package.as_ref()?;
    let lib_path = manifest
        .lib
        .as_ref()
        .and_then(|lib| lib.path.clone())
        .unwrap_or_else(|| "src/lib.rs".to_string());
    let lib = resolve_relative(rel, &lib_path)?;
    if manifest.lib.is_none() && !dir.join(&lib_path).is_file() {
        return None;
    }
    let src = lib
        .rsplit_once('/')
        .map(|(parent, _)| parent.to_string())
        .unwrap_or_default();
    let name = manifest
        .lib
        .as_ref()
        .and_then(|lib| lib.name.clone())
        .unwrap_or_else(|| package.name.clone());
    Some(Crate {
        name: crate_name(&name),
        root: rel.to_string(),
        src,
        lib,
    })
}

fn read_manifest(path: &Path) -> Option<Manifest> {
    let text = fs::read_to_string(path).ok()?;
    // A hand-edited or exotic manifest must not sink the whole run.
    toml::from_str::<Manifest>(&text).ok()
}

#[derive(Debug, Default, Deserialize)]
struct Manifest {
    package: Option<Package>,
    lib: Option<Lib>,
    workspace: Option<WorkspaceSection>,
    #[serde(default)]
    dependencies: BTreeMap<String, Dependency>,
    #[serde(default, rename = "dev-dependencies")]
    dev_dependencies: BTreeMap<String, Dependency>,
    #[serde(default, rename = "build-dependencies")]
    build_dependencies: BTreeMap<String, Dependency>,
}

#[derive(Debug, Deserialize)]
struct Package {
    name: String,
}

#[derive(Debug, Deserialize)]
struct Lib {
    name: Option<String>,
    path: Option<String>,
}

#[derive(Debug, Default, Deserialize)]
struct WorkspaceSection {
    #[serde(default)]
    members: Vec<String>,
    #[serde(default)]
    exclude: Vec<String>,
    #[serde(default)]
    dependencies: BTreeMap<String, Dependency>,
}

/// `dep = "1"` or `dep = { path = "..", workspace = true, ... }`.
#[derive(Debug, Deserialize)]
#[serde(untagged)]
enum Dependency {
    // The string is only there so untagged matching accepts `dep = "1"`; the
    // version itself is never read (crates.io is not consulted).
    Version(#[allow(dead_code)] String),
    Detailed(DetailedDependency),
}

impl Dependency {
    fn path(&self) -> Option<&str> {
        match self {
            Dependency::Version(_) => None,
            Dependency::Detailed(detailed) => detailed.path.as_deref(),
        }
    }
}

#[derive(Debug, Default, Deserialize)]
struct DetailedDependency {
    path: Option<String>,
}

#[cfg(test)]
mod tests {
    use super::*;

    fn workspace_dir(name: &str, files: &[(&str, &str)]) -> PathBuf {
        let root = std::env::temp_dir().join(format!("filer-cargo-{name}-{}", std::process::id()));
        let _ = fs::remove_dir_all(&root);
        for (rel, text) in files {
            let path = root.join(rel);
            fs::create_dir_all(path.parent().expect("nested file")).unwrap();
            fs::write(path, text).unwrap();
        }
        root
    }

    fn two_member_workspace(name: &str) -> PathBuf {
        workspace_dir(
            name,
            &[
                (
                    "Cargo.toml",
                    "[workspace]\nmembers = [\"crates/*\"]\nresolver = \"2\"\n\n[workspace.dependencies]\nmodel = { path = \"crates/model\" }\n",
                ),
                (
                    "crates/model/Cargo.toml",
                    "[package]\nname = \"model\"\nversion = \"0.1.0\"\n",
                ),
                ("crates/model/src/lib.rs", "pub mod channel;\n"),
                ("crates/model/src/channel.rs", "pub struct Channel;\n"),
                (
                    "crates/hub/Cargo.toml",
                    "[package]\nname = \"hub\"\nversion = \"0.1.0\"\n\n[dependencies]\nmodel = { path = \"../model\" }\n",
                ),
                (
                    "crates/hub/src/lib.rs",
                    "use model::channel::Channel;\n",
                ),
            ],
        )
    }

    #[test]
    fn discovers_members_by_cargo_layout() {
        let root = two_member_workspace("members");
        let workspace = Workspace::discover(&root);

        let model = workspace.crate_named("model").expect("member crate");
        assert_eq!(model.root, "crates/model");
        assert_eq!(model.src, "crates/model/src");
        assert_eq!(model.lib, "crates/model/src/lib.rs");
        assert_eq!(
            workspace.crate_named("hub").map(|k| k.root.as_str()),
            Some("crates/hub")
        );
        assert!(workspace.crate_named("serde").is_none());
        assert!(workspace.crate_at_dir("crates/model").is_some());
        assert!(workspace.crate_at_dir("crates/model/src").is_none());
        assert_eq!(
            workspace
                .crate_of("crates/model/src/channel.rs")
                .map(|k| k.name.as_str()),
            Some("model")
        );

        let _ = fs::remove_dir_all(&root);
    }

    #[test]
    fn honours_lib_name_and_path_and_renamed_dependencies() {
        let root = workspace_dir(
            "lib-names",
            &[
                ("Cargo.toml", "[workspace]\nmembers = [\"crates/core\"]\n"),
                (
                    "crates/core/Cargo.toml",
                    "[package]\nname = \"acme-core\"\nversion = \"0.1.0\"\n\n[lib]\nname = \"acme\"\npath = \"lib/main.rs\"\n",
                ),
                ("crates/core/lib/main.rs", "pub mod api;\n"),
                ("crates/core/lib/api.rs", "pub struct Api;\n"),
            ],
        );
        let workspace = Workspace::discover(&root);

        let core = workspace.crate_named("acme").expect("lib name wins");
        assert_eq!(core.src, "crates/core/lib");
        assert_eq!(core.lib, "crates/core/lib/main.rs");
        // The package name is what a `path` dependency key resolves through.
        assert!(workspace.crate_named("acme_core").is_none());

        let _ = fs::remove_dir_all(&root);
    }

    #[test]
    fn renamed_path_dependency_maps_to_the_crate_that_provides_it() {
        let root = workspace_dir(
            "renamed",
            &[
                (
                    "Cargo.toml",
                    "[workspace]\nmembers = [\"a\", \"b\"]\n\n[workspace.dependencies]\nproto = { path = \"a\", package = \"acme-protocol\" }\n",
                ),
                ("a/Cargo.toml", "[package]\nname = \"acme-protocol\"\nversion = \"0.1.0\"\n"),
                ("a/src/lib.rs", "pub struct Message;\n"),
                ("b/Cargo.toml", "[package]\nname = \"b\"\nversion = \"0.1.0\"\n"),
                ("b/src/lib.rs", ""),
            ],
        );
        let workspace = Workspace::discover(&root);

        let protocol = workspace.crate_named("proto").expect("workspace alias");
        assert_eq!(protocol.lib, "a/src/lib.rs");
        // The real package name keeps working for a plain `use acme_protocol::…`.
        assert_eq!(
            workspace
                .crate_named("acme_protocol")
                .map(|k| k.root.as_str()),
            Some("a")
        );

        let _ = fs::remove_dir_all(&root);
    }

    #[test]
    fn root_package_and_binary_only_members() {
        let root = workspace_dir(
            "root-package",
            &[
                (
                    "Cargo.toml",
                    "[package]\nname = \"app\"\nversion = \"0.1.0\"\n\n[workspace]\nmembers = [\"cli\"]\n",
                ),
                ("src/lib.rs", "pub fn run() {}\n"),
                ("cli/Cargo.toml", "[package]\nname = \"cli\"\nversion = \"0.1.0\"\n"),
                ("cli/src/main.rs", "fn main() {}\n"),
            ],
        );
        let workspace = Workspace::discover(&root);

        let app = workspace.crate_named("app").expect("root package");
        assert_eq!(app.root, "");
        assert_eq!(app.src, "src");
        // `cli` has no library target, so it is not importable by name.
        assert!(workspace.crate_named("cli").is_none());

        let _ = fs::remove_dir_all(&root);
    }

    #[test]
    fn wildcard_and_excluded_members() {
        let root = workspace_dir(
            "wildcards",
            &[
                (
                    "Cargo.toml",
                    "[workspace]\nmembers = [\"crates/*-core\"]\nexclude = [\"crates/legacy-core\"]\n",
                ),
                ("crates/alpha-core/Cargo.toml", "[package]\nname = \"alpha-core\"\nversion = \"0.1.0\"\n"),
                ("crates/alpha-core/src/lib.rs", ""),
                ("crates/legacy-core/Cargo.toml", "[package]\nname = \"legacy-core\"\nversion = \"0.1.0\"\n"),
                ("crates/legacy-core/src/lib.rs", ""),
                ("crates/other/Cargo.toml", "[package]\nname = \"other\"\nversion = \"0.1.0\"\n"),
                ("crates/other/src/lib.rs", ""),
            ],
        );
        let workspace = Workspace::discover(&root);

        assert!(workspace.crate_named("alpha_core").is_some());
        assert!(workspace.crate_named("legacy_core").is_none());
        assert!(workspace.crate_named("other").is_none());

        let _ = fs::remove_dir_all(&root);
    }

    #[test]
    fn no_manifest_is_an_empty_workspace() {
        let root = workspace_dir("empty", &[("src/lib.rs", "")]);
        let workspace = Workspace::discover(&root);
        assert!(workspace.is_empty());
        assert!(workspace.crate_named("anything").is_none());
        assert!(workspace.crate_of("src/lib.rs").is_none());

        let _ = fs::remove_dir_all(&root);
    }

    #[test]
    fn crate_files_put_the_lib_root_first() {
        let root = two_member_workspace("files");
        let workspace = Workspace::discover(&root);
        let model = workspace.crate_named("model").expect("member crate");
        let rels = ["crates/model/src/channel.rs", "crates/model/src/lib.rs"];
        let files = workspace.files_of(model, rels.iter().copied());
        assert_eq!(
            files,
            vec![
                "crates/model/src/lib.rs".to_string(),
                "crates/model/src/channel.rs".to_string()
            ]
        );

        let _ = fs::remove_dir_all(&root);
    }
}
